function RootShell({ children }: { children: ReactNode }) {
  // French is the site's default language (SSR). When a visitor switches to
  // Arabic, SiteShell updates <html lang>/<dir> on the client (→ rtl). See
  // shell.tsx's lang/dir effect.
  return (
    <html lang="fr">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
    </QueryClientProvider>
  );
}
